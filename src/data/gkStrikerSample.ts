const SAMPLE_NUMBERS = [9, 11, 7] as const;

/** Club-named draft profiles until real strikers are scouted. */
export function sampleGkStrikers(clubName: string): GkStrikerProfile[] {
  return ARCHETYPE_SHOTS.map((shots, index) => {
    const n = index + 1;
    return {
      id: `sample-${n}`,
      name: `${clubName} player ${n}`,
      number: SAMPLE_NUMBERS[index],
      isSample: true,
      shots,
      clips: [],
    };
  });
}

export function strikersForGkTab(
  profiles: GkStrikerProfile[],
  clubName: string
): GkStrikerProfile[] {
  return profiles.length > 0 ? profiles : sampleGkStrikers(clubName);
}
